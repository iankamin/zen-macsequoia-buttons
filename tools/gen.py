# Builds ../chrome.css and ../preferences.json from the glyphs in tools/build/.
import json, os
from urllib.parse import quote
HERE=os.path.dirname(os.path.abspath(__file__))

# Circle colours from MacSequoia-Dark's close/minimize/maximize SVGs
COLORS={
    'close':    ('Close button colour',    '#e9524a'),
    'minimize': ('Minimize button colour', '#f1ae1b'),
    'maximize': ('Maximize button colour', '#59c837'),
    'inactive': ('Button colour when the window is inactive', '#5d5d5d'),
}
# Zen class suffix -> (glyph file, colour setting)
BUTTONS={'close':('close','close'),'min':('minimize','minimize'),
         'max':('maximize','maximize'),'restore':('restore','maximize')}

def uri(f):
    s=open(os.path.join(HERE,'build',f)).read().replace('"',"'")
    return 'url("data:image/svg+xml,'+quote(s,safe=" '=:/;,.-()")+'")'

# Zen exposes a "string" preference as --<property with dots as hyphens>
colour_vars='\n'.join(
    f'  --tl-{k}: var(--mod-macsequoia-{k}_color, {default});'
    for k,(_,default) in COLORS.items())
glyph_vars='\n'.join(f'  --tl-{k}-glyph: {uri(f"{g}-glyph.svg")};' for k,(g,_) in BUTTONS.items())
rules='\n'.join(f'''.titlebar-{k} {{ background-color: var(--tl-{c}) !important; }}
.titlebar-{k}:hover {{ background-image: var(--tl-{k}-glyph) !important; }}
.titlebar-{k}:hover:active {{ background-image: var(--tl-{k}-glyph), var(--tl-pressed) !important; }}'''
    for k,(_,c) in BUTTONS.items())

css=f'''/* MacSequoia Window Buttons
 * Draws Zen's minimize / maximize / close buttons as the traffic lights of
 * the MacSequoia-Dark Aurorae window decoration, so they match KWin's.
 * Each button is a 14px circle in a 16px box, with the theme's own glyph on
 * hover and a 20% darkening while pressed, as in the theme's SVGs.
 * Generated by tools/gen.py; see the readme to regenerate.
 */

:root {{
  --tl-button-size: 16px;   /* ButtonWidth / ButtonHeight in MacSequoia-Darkrc */
  --tl-button-gap: 10px;    /* ButtonSpacing */

  /* Colours come from the mod's settings; the fallbacks are the theme's.
   * Using this as userChrome.css? Change the fallback values here. */
{colour_vars}

  --tl-pressed: linear-gradient(rgb(0 0 0 / 0.2), rgb(0 0 0 / 0.2));
{glyph_vars}
}}

.titlebar-buttonbox {{
  align-items: center !important;
  gap: var(--tl-button-gap) !important;
  padding-inline: 8px !important;
}}

/* The circle is the background clipped to the content box: 1px padding
 * leaves a 14px circle, and the glyph is laid out over the full 16px */
.titlebar-button {{
  appearance: none !important;
  align-self: center !important;
  width: var(--tl-button-size) !important;
  height: var(--tl-button-size) !important;
  min-width: var(--tl-button-size) !important;
  min-height: var(--tl-button-size) !important;
  margin: 0 !important;
  padding: 1px !important;
  border: none !important;
  border-radius: 50% !important;
  background-image: none !important;
  background-clip: content-box !important;
  background-origin: border-box !important;
  background-position: center !important;
  background-repeat: no-repeat !important;
  background-size: 100% 100% !important;
  opacity: 1 !important;
}}

/* The glyphs are drawn as backgrounds, so hide Zen's own icons */
.titlebar-button > image {{
  display: none !important;
}}

{rules}

:root:-moz-window-inactive .titlebar-button {{
  background-color: var(--tl-inactive) !important;
}}
'''
open(os.path.join(HERE,'..','chrome.css'),'w').write(css)

prefs=[{'property':f'mod.macsequoia.{k}_color','label':label,'type':'string',
        'placeholder':f'{default} (theme default)'}
       for k,(label,default) in COLORS.items()]
open(os.path.join(HERE,'..','preferences.json'),'w').write(json.dumps(prefs,indent=4)+'\n')
print(len(css),'bytes of CSS,',len(prefs),'preferences')
